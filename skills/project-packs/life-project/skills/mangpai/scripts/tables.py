# 长生位：阳干顺行，阴干逆行（盲派同此，原文多处印证：丙戊长生在寅、丁己长生在酉、
# 庚长生在巳、壬长生在申、甲长生在亥、乙长生在午、辛长生在子、癸长生在卯）
CHANGSHENG_START = {
    "甲": "亥", "乙": "午", "丙": "寅", "丁": "酉", "戊": "寅",
    "己": "酉", "庚": "巳", "辛": "子", "壬": "申", "癸": "卯",
}


def changsheng(gan: str, zhi: str) -> str:
    start = DIZHI.index(CHANGSHENG_START[gan])
    idx = DIZHI.index(zhi)
    step = (idx - start) % 12 if GAN_YINYANG[gan] else (start - idx) % 12
    return CHANGSHENG_ORDER[step]


def changsheng_pos(gan: str, name: str) -> str:
    """求某天干的某个长生位落在哪个地支。"""
    start = DIZHI.index(CHANGSHENG_START[gan])
    step = CHANGSHENG_ORDER.index(name)
    idx = (start + step) % 12 if GAN_YINYANG[gan] else (start - step) % 12
    return DIZHI[idx]


