def shishen(rigan: str, target: str) -> str:
    """以日干为基准求某天干的十神。"""
    rw, tw = GAN_WUXING[rigan], GAN_WUXING[target]
    same_yy = GAN_YINYANG[rigan] == GAN_YINYANG[target]
    if rw == tw:
        return "比肩" if same_yy else "劫财"
    if SHENG[rw] == tw:                       # 我生
        return "食神" if same_yy else "伤官"
    if KE[rw] == tw:                          # 我克
        return "偏财" if same_yy else "正财"
    if KE[tw] == rw:                          # 克我
        return "七杀" if same_yy else "正官"
    return "偏印" if same_yy else "正印"       # 生我


