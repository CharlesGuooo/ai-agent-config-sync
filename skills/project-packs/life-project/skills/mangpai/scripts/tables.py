def jiazi_index(gan: str, zhi: str) -> int:
    """六十甲子序号（0-59）。"""
    gi, zi = TIANGAN.index(gan), DIZHI.index(zhi)
    for n in range(60):
        if n % 10 == gi and n % 12 == zi:
            return n
    raise ValueError(f"非法干支组合：{gan}{zhi}")


def nayin(gan: str, zhi: str) -> str:
    return NAYIN_60[jiazi_index(gan, zhi)]


def xunshou(gan: str, zhi: str) -> str:
    """求该柱所属旬（旬首）。"""
    n = jiazi_index(gan, zhi)
    return TIANGAN[(n - n % 10) % 10] + DIZHI[(n - n % 10) % 12]


def kongwang(gan: str, zhi: str):
    """求该柱的旬空两支。"""
    return XUNKONG[xunshou(gan, zhi)]


